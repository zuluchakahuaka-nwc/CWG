// Generates map_data.json with real US state outlines from lat/lon
// Equirectangular projection, Civil War era (1861-1865 borders)
const fs = require('fs');

// Projection: x = (lon - MIN_LON) * SCALE_X, y = (MAX_LAT - lat) * SCALE_Y
const MIN_LON = -107;
const MAX_LON = -67;
const MIN_LAT = 24;
const MAX_LAT = 48;
const W = 1200;
const H = 850;
const SX = W / (MAX_LON - MIN_LON);
const SY = H / (MAX_LAT - MIN_LAT);

function project(coords) {
  return coords.map(([lat, lon]) => [
    Math.round((lon - MIN_LON) * SX * 100) / 100,
    Math.round((MAX_LAT - lat) * SY * 100) / 100
  ]);
}


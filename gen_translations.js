for (let i = 0; i < lines.length; i++) {
  const parts = lines[i].split(',');
  const key = parts[0];
  const row = { key };
  for (let j = 1; j < parts.length && j < header.length; j++) {
    row[header[j]] = parts[j];
  }
  parsedLines.push(row);
}

let output = 'key,' + allLangs.join(',') + '\n';
for (const row of parsedLines) {
  let line = row.key;
  for (const lang of allLangs) {
    if (row[lang] !== undefined) {
      line += ',' + row[lang];
    } else if (translations[lang] && translations[lang][row.key]) {
      line += ',' + translations[lang][row.key];
    } else {
      const enVal = row['en'] || row[existingLangs[1]] || '';
      line += ',' + enVal;
    }
  }
  output += line + '\n';
}

